"""Идентификаторы: хеш идентификатора человека для трасс и журналов.

В трассы и журналы не должен попадать `chat_id` как есть: хеша хватает, чтобы связать события одного
клиента между собой.
"""
from __future__ import annotations

import hashlib


def chat_hash(value: str) -> str:
    """Короткий хеш идентификатора клиента для отчётов и трасс.

    В таблицах, которые читает человек (трассы, отчёты), `chat_id` не хранится: он сам по себе
    идентификатор человека в мессенджере. Хеша хватает, чтобы связать строки одного клиента между
    собой, и недостаточно, чтобы узнать, кто это.
    """
    return hashlib.sha256((value or "").encode()).hexdigest()[:16]
