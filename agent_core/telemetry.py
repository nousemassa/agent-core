"""Трассировка ходов: спаны уходят прямо в приём OTLP платформы.

**Зачем именно так.** У платформы есть приём `POST {PLATFORM_API_URL}/otlp/v1/traces` (тело —
protobuf, заголовок `Authorization: ApiKey …`, право `EDIT_SPANS`) и интерфейс трейсов
(`/w/{workspace}/p/{project}/observability`). Коллектор из vendor **не нужен**: его файлы в стек не
входят, и контейнера с ним нет. **Атрибуты ресурса приём игнорирует
полностью**, поэтому `service.name` в них — для человека, а не для фильтра: привязка к нашему агенту
идёт АТРИБУТАМИ СПАНА, а их форму собирает адаптер вендора (`vendors/`). У второго приёмника
(OpenLIT) `service.name` — наоборот, ключ группировки; поэтому состав ресурса решает ВЕНДОР
(`vendors/port.py::resource_attributes`), а не этот модуль.

**Почему модуль один.** Это единственное место, которое знает про OTLP, HTTP-экспортёр и настройки
трассировки; остальной код получает только трейсер и открывает спаны. Необязательная зависимость
(`opentelemetry-*`) импортируется ровно здесь — тем же правилом, что и любая необязательная зависимость: нет пакета —
работает прежний путь, и это не аварийная деградация, а штатное состояние.

**Деградация молчаливая и по двум причинам сразу:** не задан адрес (`OTEL_ENDPOINT`) или не
установлены пакеты — трейсер-пустышка. Спаны в этом случае не создаются, сервис работает как раньше.

**Что здесь НЕ живёт.** Форма атрибутов, адрес приёма и состав ресурса: и то, и другое, и
третье — дело ВЕНДОРА. Здесь остаётся транспорт, общий для обоих вендоров (экспортёр, батч, досылка).
Адрес спрашивается у активного адаптера (`vendors.active().receiver(settings)`) — иначе при
`PLATFORM_VENDOR=openlit` спаны молча уезжали бы в Agenta.

**Почему трейсеров несколько.** Владелец хотел видеть в приёмнике не «одну службу на
процесс», а **отдельного агента на роль**. `service.name` —
свойство ПРОВАЙДЕРА, а не спана, поэтому ролей столько же, сколько провайдеров: в одном процессе
их может быть несколько (две роли живут рядом), у отдельного графа — своя. Глобальным
(`set_tracer_provider`) регистрируется ПЕРВЫЙ собранный: встроенная телеметрия FastAPI берёт именно
его, и пятый провайдер «сам собой» не появляется. Формулировка «агент» здесь = роль, под которой наши
спаны видны в UI; `AGENT_RUNTIME` (`platform|own|auto`) — другая ось, и её это не касается.
"""

from __future__ import annotations

import atexit
import logging

from agent_core import vendors
from agent_core.ids import chat_hash

log = logging.getLogger(__name__)

#: Роли, под которыми наши службы видны в приёмнике. Значения — ЧАСТЬ КОНТРАКТА С UI: из них строится
#: `service.name` и от них зависит, покажет ли приёмник агента в своём списке. Поэтому неизвестная роль
#: — громкий отказ, а не молчаливое «ну, будет ещё одна служба»: опечатка в имени роли создала бы
#: пятый «агент», которого никто не заводил, и искала бы его владелец.
#: Роли регистрирует продукт при старте: ядро имён ролей не знает.
_ROLES: set[str] = set()


def register_roles(*roles: str) -> None:
    """Объявить роли, под которыми службы процесса видны в приёмнике."""
    _ROLES.update(role.strip().lower() for role in roles if role and role.strip())

#: Собранные трейсеры по ключу `(адрес приёма, имя службы)`: `set_tracer_provider` можно вызвать в
#: процессе только ОДИН раз, поэтому повторная сборка не просто бесполезна — она осиротеет (провайдер
#: создан, но не зарегистрирован), и `flush_telemetry` будет досылать не тот провайдер. Пока спаны
#: спасает таймер батча.
_TRACERS: dict[tuple[str, str], object] = {}
#: Все СВОИ провайдеры — для досылки на выходе. Список, а не один: ролей несколько (см. докстроку).
_PROVIDERS: list[object] = []
#: Роль, чей провайдер зарегистрирован глобальным (`trace.set_tracer_provider`) — её же видит встроенная
#: телеметрия FastAPI. Второй вызов `set_tracer_provider` запрещён, и это не наша беда: роли различаются
#: ПРОВАЙДЕРОМ, а не глобальной регистрацией.
_PRIMARY_AGENT: str | None = None


def service_name(agent: str) -> str:
    """Имя службы для роли: `agent-<роль>`.

    Имя строится по ФУНКЦИИ, а не по вендору: `agent-<роль>` переживёт смену вендора, имя с префиксом
    вендора — нет. Спаны, записанные раньше, сохраняют прежние имена: это история, а не действующее правило.
    """
    name = (agent or "").strip().lower()
    if name not in _ROLES:
        raise ValueError(
            f"неизвестная роль агента {agent!r}: зарегистрированы {', '.join(sorted(_ROLES))}. "
            f"Новое имя роли — это новый «агент» в приёмнике, поэтому оно объявляется здесь, а не в вызове."
        )
    return f"agent-{name}"


def tracer_resource(settings, agent: str) -> dict:
    """Атрибуты РЕСУРСА, которые получат спаны этой роли (что именно — решает активный вендор).

    Отдельной функцией, а не строкой внутри `setup_telemetry`: это единственное место, где имя роли
    превращается в атрибуты провайдера, и его видно тесту — иначе «у каждой роли своя служба» держалось
    бы только на честном слове.
    """
    return vendors.active().resource_attributes(settings, service_name(agent))


def span_attributes(*, workflow_id: str, workflow_slug: str, chat_id: str = "", step: str = "") -> dict:
    """Ссылки спана хода: воркфлоу, шаг и (хешированная) ссылка на сессию клиента.

    **Тип спана здесь НЕ объявляется — и это форма, а не недоделка.** Спан хода уходил так с
    самого начала, принимающая сторона оставляет ему тип по умолчанию, и эту форму НЕ
    меняет: смена типа — смена формы трейса, это отдельное решение. Отсюда и `kind=None` в нейтральной
    модели: «тип не объявлен» — отдельный измеренный случай, а не «забыли заполнить».

    Идентификатор клиента хешируется ЗДЕСЬ, а не у вызывающего: в трейс не должен попасть `chat_id`
    как есть — это идентификатор человека в мессенджере, а хеша хватает, чтобы связать спаны одного
    клиента между собой. Правило то же, что у трасс ходов.
    """
    return vendors.active().attributes(vendors.SpanShape(
        session_id=chat_hash(chat_id) if chat_id else "",
        workflow_id=workflow_id,
        workflow_slug=workflow_slug,
        step=step,
    ))


def setup_telemetry(settings, agent: str) -> object:
    """Собрать трейсер РОЛИ `agent` или вернуть пустышку. Единственный вход к трассировке.

    Пустышка — это настоящий `ProxyTracer` из `opentelemetry-api` без провайдера: `with
    tracer.start_as_current_span(...)` работает как ничего не делающий контекст, поэтому вызывающий
    код не обрастает проверками «а включена ли трассировка». Это и есть причина, по которой точки
    спанов можно расставлять заранее, не боясь, что они чего-то потребуют.

    Один адрес + одна роль ⇒ ОДИН провайдер и ОДИН трейсер на всё время жизни процесса: пересборка
    осиротит досылку. Одна роль в разных процессах — разные провайдеры, и это нормально: провайдер
    живёт в процессе.
    """
    global _PRIMARY_AGENT
    # ❗ ВЫБОР ВЕНДОРА — ПЕРВОЙ СТРОКОЙ, до кэш-выхода ниже. Иначе повторный вызов с тем же адресом
    # вернул бы кэшированный трейсер и вендора НЕ пересмотрел: смена `PLATFORM_VENDOR` прошла бы молча.
    # Ось наблюдаемости: `TELEMETRY_VENDOR`, если задана, иначе `PLATFORM_VENDOR`.
    # ❗ Ось читается ЗДЕСЬ и только здесь — это единственный вход к трассировке (см. докстроку выше).
    # ❗ ОДНА формула на выбор и на журнал: две формулы дают разное имя — в выборе одно, в журнале
    # другое.
    telemetry_vendor = (
        getattr(settings, "telemetry_vendor", "") or getattr(settings, "platform_vendor", "") or vendors.AGENTA
    )
    vendors.select(telemetry_vendor)
    # Адрес и авторизация — дело ВЕНДОРА, а не наше: оставь их литералом здесь, и при
    # `PLATFORM_VENDOR=openlit` спаны молча уезжали бы в Agenta.
    receiver = vendors.active().receiver(settings)
    endpoint = receiver.endpoint
    # Имя службы — ДО кэша: опечатка в роли обязана отказать громко, а не завести нового «агента».
    name = service_name(agent)
    key = (endpoint, name)
    cached = _TRACERS.get(key)
    if cached is not None:
        return cached
    try:
        from opentelemetry import trace
    except ImportError:  # необязательная зависимость: без неё живём как раньше
        log.warning("telemetry: пакеты OpenTelemetry не установлены — трассировки не будет")
        return None

    if not endpoint:
        # Пустой адрес — штатное состояние (трассировка выключена), а не ошибка настройки:
        # поэтому здесь НЕ warning, иначе журнал ругался бы на каждой установке по умолчанию.
        _TRACERS[key] = trace.get_tracer(name)
        return _TRACERS[key]

    from opentelemetry.exporter.otlp.proto.http.trace_exporter import OTLPSpanExporter
    from opentelemetry.sdk.resources import Resource
    from opentelemetry.sdk.trace import TracerProvider
    from opentelemetry.sdk.trace.export import BatchSpanProcessor

    # Состав ресурса — от вендора (`resource_attributes`): `service.name` у одного приёмника декоративен,
    # у другого — ключ группировки и условие появления агента в UI. Литерал здесь означал бы, что
    # `core` знает чужие правила обнаружения.
    provider = TracerProvider(resource=Resource.create(tracer_resource(settings, agent)))
    # **БАТЧЕВЫЙ экспорт, а не поштучный — и это не оптимизация, а условие целостности дерева.**
    # Приём платформы строит лес спанов по БАТЧУ: «спан, чей родитель не пришёл в этом же запросе,
    # считается корнем» (так устроен приёмник платформы). С поштучным экспортом каждый ребёнок
    # ехал отдельным запросом, объявлялся корнем и конфликтовал с уже записанным корнем того же
    # трейса — в базе оставался ОДИН корень без детей: корень есть, ролей нет. Батч отправляет всё
    # дерево одним запросом, и дети остаются детьми.
    #
    # ❗ Батч остаётся ЗДЕСЬ, а не переезжает в адаптер вендора: правило «корень = спан без родителя в
    # партии» — вендорское, но у второго приёмника его НЕТ (там родитель держится `parent_span_id`), и
    # переносить сюда нечего. При таймере 1 с и дереве выпуска 5–7 с дерево ЦЕЛО, и
    # метрики приём пересчитывает сам после каждой партии (воркер ингеста) — поэтому менять таймер
    # нечем и незачем.
    provider.add_span_processor(BatchSpanProcessor(
        OTLPSpanExporter(endpoint=receiver.endpoint, headers=receiver.headers, timeout=5.0),
        schedule_delay_millis=1000,      # дерево выпуска живёт секунды: минуты ожидания не нужны
        max_export_batch_size=512,       # трейс выпуска целиком уходит одним запросом
    ))
    if _PRIMARY_AGENT is None:
        # Глобальным регистрируется ПЕРВЫЙ: встроенная телеметрия FastAPI берёт глобальный провайдер, и
        # без этой строки её спаны молча уходили бы в пустоту. Второй вызов запрещён самим OTEL.
        trace.set_tracer_provider(provider)
        _PRIMARY_AGENT = name
        atexit.register(flush_telemetry)  # короткие процессы (скрипты) досылают спаны на выходе
    _PROVIDERS.append(provider)
    # Вендор и приём называем в журнале: переключение флагом обязано быть ВИДНО, иначе «спаны не там» —
    # неотличимо от «спанов нет», и разбор начинается вслепую. Имя службы печатаем тоже: именно его
    # владелец ищет в UI, и именно оно объясняет, почему агентов несколько.
    log.info("telemetry: служба %s → %s (вендор=%s, привязка workflow=%s)",
             name, endpoint, telemetry_vendor,
             getattr(settings, "otel_workflow_slug", "") or "—")
    # ❗ Трейсер берём У ПРОВАЙДЕРА, а не `trace.get_tracer(name)`: глобальный провайдер один, и у
    # второй роли в том же процессе спаны уехали бы под именем первой.
    _TRACERS[key] = provider.get_tracer(name)
    return _TRACERS[key]


#: Пути, которые не трассируются: проверки живости и скрейп метрик. Сравнение ПРЕФИКСНОЕ по корню и
#: ПО ПОСЛЕДНЕМУ СЕГМЕНТУ: у MCP и графа свои листенеры (`/mcp/health`), и они обязаны молчать так же,
#: как `/health` сервиса — иначе шум возвращается с другой стороны.
_QUIET_PATHS = ("/health", "/metrics", "/readyz")
_QUIET_NAMES = frozenset(path.lstrip("/") for path in _QUIET_PATHS)


def _skip_quiet_paths(scope) -> bool:
    """`True` — FastAPI не трогает этот запрос. Принимает ASGI-scope, как требует его же API."""
    path = str(scope.get("path") or "")
    return path.startswith(_QUIET_PATHS) or path.rstrip("/").rsplit("/", 1)[-1] in _QUIET_NAMES


def fastapi_telemetry() -> dict:
    """Настройка ВСТРОЕННОЙ телеметрии FastAPI — `FastAPI(telemetry=agent_core.telemetry.fastapi_telemetry())`.

    **Зачем.** С 0.143 FastAPI сам трассирует КАЖДЫЙ HTTP-запрос и по умолчанию пишет четыре спана
    (`GET /health` + `fastapi.endpoint` + `fastapi.dependencies` + `fastapi.serialization`). Проверки
    живости дёргают HEALTHCHECK и сторожа, поэтому в приёмник лился поток служебных спанов: замер
    показал **2 259 из 2 269** спанов на `/health`, и настоящие трейсы в списке было не найти.

    **Что делаем.** (1) Не трассируем служебные пути вовсе; (2) выключаем `operation_spans`: на реальный
    запрос остаётся ОДИН спан вместо четырёх. Сами спаны хода (`turn`, `visit.flow`) не задеты — их
    создаёт наш код.

    **Чего НЕ делаем.** Не глушим телеметрию целиком (`tracing=False`): HTTP-спан бизнес-ручки — полезная
    запись, и именно по ней видно, что запрос был.
    """
    return {"exclude": _skip_quiet_paths, "operation_spans": False}


def flush_telemetry() -> None:
    """Дослать не отправленные спаны ВСЕХ ролей. Нужна перед выходом процесса: батч ждёт интервала.

    Без этого короткий процесс (измеритель, скрипт) завершается раньше, чем батч уйдёт, и трейс
    теряется — а «спанов нет» выглядело бы как «трассировка не работает».
    """
    for provider in _PROVIDERS:
        try:
            provider.force_flush(timeout_millis=5000)
        except Exception as error:  # noqa: BLE001 — ошибка досылки не ломает завершение процесса
            log.warning("telemetry: досылка спанов не удалась (%s: %s)", type(error).__name__, error)


def trace_id() -> str:
    """Идентификатор текущего трейса в hex — 32 знака, как его печатает платформа.

    Пустая строка, когда спана нет (трассировка выключена): в этом случае в трассе хода и в журнале
    остаётся пусто, а не ноль — «трейса нет» и «трейс нулевой» разные состояния.
    """
    try:
        from opentelemetry import trace
    except ImportError:
        return ""
    span = trace.get_current_span()
    context = span.get_span_context() if span else None
    if context is None or not getattr(context, "is_valid", False):
        return ""
    return f"{context.trace_id:032x}"


def span(tracer, name: str, attributes: dict | None = None, *, record_exceptions: bool = True):
    """Открыть спан — ДЕЛЕГАТ в `spans.span`, не второй вход.

    **Почему делегат, а не своя реализация.** Здесь стояла ВТОРАЯ реализация той же операции,
    и докстринг называл её «единственной точкой создания спанов» — при том, что рядом, в `spans.py`, жила
    вторая, и они расходились по поведению: `spans.span` передаёт `record_exception` и
    `set_status_on_exception`, а эта — нет. Следствие было не косметическим: один контур закрывал
    исключения по умолчанию OTel (исключение = ошибка спана), а другой — по своему правилу
    (приостановка графа ошибкой не считается), поэтому ОДНО И ТО ЖЕ событие в двух контурах давало
    разный статус в трейсах.

    Теперь контракт один и живёт в `spans.span`; здесь остаётся совместимость: старые вызовы
    (`telemetry.span(...)`) работают и получают то же поведение, что и новые. `attributes` стал
    необязательным — у хода он есть не всегда.
    """
    from agent_core import spans

    return spans.span(tracer, name, attributes or {}, record_exceptions=record_exceptions)
