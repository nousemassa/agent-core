"""Подсказка о покрытии вопроса найденными фрагментами. Только чистые функции.

**Это ПОДСКАЗКА, а не приговор — и вот почему, измерено на наборе вопросов:**

| Пример | Совпало слов | Ответ есть | Подсказка верна? |
|---|---|---|---|
| 1 | 1/4 | нет | да |
| 2 | 4/4 | есть | да |
| 3 | 4/4 | есть | да |
| 4 | 2/4 | есть | да |
| 5 | 2/4 | нет | **нет: ложное «есть»** |
| 6 | 1/4 | есть | **нет: ложное «нет»** |
| 7 | 3/4 | нет | **нет: ложное «есть»** |

Ошибки **в обе стороны**, поэтому порога здесь СОЗНАТЕЛЬНО нет: совпадение слов не равно совпадению
смысла — поиск приносит фрагменты с общими словами и другим смыслом, а нужный фрагмент бывает ниже в
выдаче. Разница между «фрагмент отвечает на заданный вопрос» и «на соседний» семантическая, и видит её
только модель.

Значит назначение модуля узкое: дать вызывающему **факт** о совпадениях как один из входов, а решение
оставить ему. Порог по этим числам не вводить — иначе система начнёт уточнять там, где ответ есть, и
отвечать там, где его нет.
"""
from __future__ import annotations

import re
from collections.abc import Sequence

# Стоп-слова: явным списком, как принято в проекте. Только то, что реально мешает считать
# совпадения в обычных вопросах пользователей.
STOPWORDS = frozenset({
    "какие", "какой", "какая", "какое", "каков", "нужны", "нужно", "надо", "для", "про",
    "что", "как", "чем", "чём", "если", "или", "это", "мне", "меня", "мы", "вы", "вас",
    "ваш", "ваша", "есть", "быть", "можно", "нельзя", "при", "над", "под", "без",
    "также", "тоже", "еще", "ещё", "уже", "только", "очень", "самый", "весь", "все", "всё",
    "когда", "где", "куда", "почему", "зачем", "сколько", "стоит", "хочу", "хотел",
})

_WORD_RE = re.compile(r"[а-яёa-z0-9]{4,}")
_PREFIX_LEN = 5


def significant_words(text: str) -> set[str]:
    """Значимые слова текста: без стоп-слов, усечённые до основы.

    Усечение до пяти знаков — грубое подобие основы: «сделка/сделки/сделке» → «сделк».
    Полноценная лемматизация сюда не тянется: на решении это не сказывается (см. докстроку
    модуля), а лишняя зависимость была бы настоящей.
    """
    lowered = (text or "").lower().replace("ё", "е")
    return {
        word[:_PREFIX_LEN]
        for word in _WORD_RE.findall(lowered)
        if word not in STOPWORDS
    }


def coverage_hint(question: str, fragments: Sequence[str], topics: Sequence[str] = ()) -> str:
    """Строка подсказки для контекста хода. Пустая строка — подсказывать нечего.

    Возвращает факт, а не вердикт: сколько фрагментов поделили значимые слова с вопросом и
    какая тема из списка ближе всех. Формулировка намеренно говорит, что малое совпадение не
    значит «ответа нет», а большое — «ответ есть».
    """
    fragment_list = [fragment for fragment in fragments if fragment]
    if not fragment_list:
        # Пустая выдача — самый ясный случай: отвечать нечем. Подсказка обязана быть и здесь,
        # иначе блок порядка пропадёт ровно там, где он нужнее всего.
        return ("Покрытие вопроса (факт): не найдено ни одного фрагмента — ответа в базе под "
                "этот вопрос нет. Уточняй, чем помочь.")

    question_words = significant_words(question)
    matched = sum(1 for fragment in fragment_list if significant_words(fragment) & question_words)

    closest = ""
    best_overlap = 0
    for topic in topics:
        overlap = len(significant_words(topic) & question_words)
        if overlap > best_overlap:
            closest, best_overlap = topic, overlap

    return (
        f"Покрытие вопроса (ПОДСКАЗКА, а не приговор): значимые слова совпали у {matched} "
        f"из {len(fragment_list)} фрагментов"
        + (f"; ближе всех тема «{closest}»" if closest else "")
        + ". Малое совпадение не значит, что ответа нет, а большое — что он есть: "
          "сравнивай смысл вопроса и фрагментов, а не слова."
    )
