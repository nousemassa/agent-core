"""Тесты подсказки о покрытии вопроса.

Смысл тестов — зафиксировать, что это **подсказка**, а не мера: считает она факты, а решения
не принимает. Ошибочные случаи из докстроки модуля проверяются здесь как ИЗВЕСТНОЕ ограничение, а не как
истина — чтобы никто, прочитав тест, не начал строить на этих числах порог.
"""
from __future__ import annotations

from agent_core.retrieval.coverage import coverage_hint, significant_words


def test_significant_words_drops_stopwords_and_matches_forms():
    """Стоп-слова уходят, а формы одного слова сходятся — иначе считать нечего."""
    words = significant_words("Какие документы нужны для проверки сделки?")

    assert "докум" in words and "прове" in words and "сделк" in words
    assert not words & {"какие", "нужны", "для"}


def test_coverage_hint_reports_empty_retrieval_as_a_fact():
    """Пустая выдача — самый ясный случай, и подсказка обязана быть именно здесь."""
    hint = coverage_hint("какие документы нужны для сделки", [])

    assert "ни одного фрагмента" in hint and "Уточняй" in hint


def test_coverage_hint_counts_matches_and_names_closest_topic():
    hint = coverage_hint(
        "чем регламент отличается от инструкции",
        ["Регламент. Основные отличия регламента от инструкции: если регламент…",
         "Справка. Порядок выдачи…"],
        topics=["Инструкция", "Справка", "Регламент"],
    )

    assert "1 из 2" in hint or "2 из 2" in hint
    # При равном совпадении тем побеждает первая в списке — это не ошибка, а порядок:
    # проверяем факт «тема названа», а не то, какая именно оказалась ближе.
    assert "ближе всех тема" in hint
    assert "ПОДСКАЗКА, а не приговор" in hint


def test_coverage_hint_never_claims_absence():
    """Формулировка обязана запрещать вывод «ответа нет» из малого совпадения.

    Живой случай: вопрос даёт одно совпадение по общему слову, при том что нужный фрагмент в
    выдаче есть. Если подсказка начнёт звучать как вердикт, сервис будет уточнять там, где уже
    есть что ответить.
    """
    hint = coverage_hint("что такое сертификация и как её проверить", ["общий раздел. краткая справка"])

    assert "не значит, что ответа нет" in hint


def test_known_weakness_is_documented_in_the_module():
    """Таблица ошибок остаётся в модуле: она объясняет, почему порога тут нет."""
    from agent_core.retrieval import coverage

    doc = coverage.__doc__ or ""
    assert "| Пример |" in doc, "таблица замеров обязана остаться в модуле"
    assert "ложное" in doc
